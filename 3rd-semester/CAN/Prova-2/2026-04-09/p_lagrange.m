 x1 = 1;
 y1 = 4;
 x2 = 2;
 y2 = 7;
 x3 = 3;
 y3 = 6;
 
 x =2.5;
 
 l1 = ( (x - x2) * (x - x3) ) / ( (x1 - x2) * (x1 - x3) ) ;
 
 l2 = ( (x - x1) * (x - x3) ) / ( (x2 - x1) * (x2 - x3) );

 l3 = ( (x - x1) * (x - x2) ) / ( (x3 - x1) * (x3 - x2)); 
 
 f = y1 * l1 + y2 * l2 + y2 * l3
 
 plot([x1 x2 x3],[y1 y2 y3], '*',x,f,'o')